-- ============================================================
-- 3. USERS
-- ============================================================

CREATE TABLE users (
    id UUID PRIMARY KEY DEFAULT uuidv7(),

    name VARCHAR(100) NOT NULL,

    email VARCHAR(255) NOT NULL UNIQUE,

    password VARCHAR(255) NOT NULL,

    role user_role NOT NULL DEFAULT 'USER',

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- ============================================================
-- 4. EO APPLICATIONS
-- ============================================================

CREATE TABLE eo_applications (
    id UUID PRIMARY KEY DEFAULT uuidv7(),

    user_id UUID NOT NULL,

    status eo_application_status NOT NULL DEFAULT 'PENDING',

    reason TEXT,

    rejection_reason TEXT,

    reviewed_by UUID,

    reviewed_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_eo_application_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_eo_application_reviewer
        FOREIGN KEY (reviewed_by)
        REFERENCES users(id)
        ON DELETE SET NULL
);


-- ============================================================
-- 5. CATEGORIES
-- Lookup table -> BIGINT AUTO INCREMENT
-- ============================================================

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(100) NOT NULL UNIQUE,

    slug VARCHAR(120) NOT NULL UNIQUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- ============================================================
-- 6. EVENTS
-- ============================================================

CREATE TABLE events (
    id UUID PRIMARY KEY DEFAULT uuidv7(),

    eo_id UUID NOT NULL,

    category_id BIGINT NOT NULL,

    title VARCHAR(200) NOT NULL,

    slug VARCHAR(220) NOT NULL UNIQUE,

    description TEXT NOT NULL,

    event_type event_type NOT NULL,

    venue_name VARCHAR(200),

    address TEXT,

    online_url TEXT,

    starts_at TIMESTAMPTZ NOT NULL,

    ends_at TIMESTAMPTZ NOT NULL,

    banner_path TEXT,

    status event_status NOT NULL DEFAULT 'DRAFT',

    rejection_reason TEXT,

    reviewed_by UUID,

    reviewed_at TIMESTAMPTZ,

    cancelled_at TIMESTAMPTZ,

    cancellation_reason TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_event_eo
        FOREIGN KEY (eo_id)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_event_category
        FOREIGN KEY (category_id)
        REFERENCES categories(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_event_reviewer
        FOREIGN KEY (reviewed_by)
        REFERENCES users(id)
        ON DELETE SET NULL,

    CONSTRAINT chk_event_time
        CHECK (ends_at > starts_at),

    CONSTRAINT chk_event_location
        CHECK (
            (
                event_type = 'OFFLINE'
                AND venue_name IS NOT NULL
                AND address IS NOT NULL
            )
            OR
            (
                event_type = 'ONLINE'
                AND online_url IS NOT NULL
            )
        )
);


-- ============================================================
-- 7. EVENT STAFF
-- ============================================================

CREATE TABLE event_staff (
    id UUID PRIMARY KEY DEFAULT uuidv7(),

    event_id UUID NOT NULL,

    user_id UUID NOT NULL,

    role event_staff_role NOT NULL DEFAULT 'CHECKIN',

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_event_staff_event
        FOREIGN KEY (event_id)
        REFERENCES events(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_event_staff_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_event_staff_event_user
        UNIQUE (event_id, user_id)
);


-- ============================================================
-- 8. TICKET TYPES
-- ============================================================

CREATE TABLE ticket_types (
    id UUID PRIMARY KEY DEFAULT uuidv7(),

    event_id UUID NOT NULL,

    name VARCHAR(100) NOT NULL,

    description TEXT,

    quota INTEGER NOT NULL,

    sale_start TIMESTAMPTZ,
    sale_end TIMESTAMPTZ,

    status ticket_price_status NOT NULL DEFAULT 'ACTIVE',

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_ticket_type_event
        FOREIGN KEY (event_id)
        REFERENCES events(id)
        ON DELETE CASCADE,

    CONSTRAINT chk_ticket_type_quota
        CHECK (quota >= 0),

    CONSTRAINT chk_ticket_type_sale_period
        CHECK (
            sale_end IS NULL
            OR sale_start IS NULL
            OR sale_end > sale_start
        ),

    CONSTRAINT uq_ticket_type_event_name
        UNIQUE (event_id, name)
);


-- ============================================================
-- 9. TICKET PRICES
-- ============================================================

CREATE TABLE ticket_prices (
    id UUID PRIMARY KEY DEFAULT uuidv7(),

    ticket_type_id UUID NOT NULL,

    name VARCHAR(100) NOT NULL,

    price NUMERIC(14,2) NOT NULL,

    starts_at TIMESTAMPTZ,

    ends_at TIMESTAMPTZ,

    status ticket_price_status NOT NULL DEFAULT 'ACTIVE',

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_ticket_price_ticket_type
        FOREIGN KEY (ticket_type_id)
        REFERENCES ticket_types(id)
        ON DELETE CASCADE,

    CONSTRAINT chk_ticket_price_amount
        CHECK (price >= 0),

    CONSTRAINT chk_ticket_price_period
        CHECK (
            ends_at IS NULL
            OR starts_at IS NULL
            OR ends_at > starts_at
        ),

    CONSTRAINT uq_ticket_price_name
        UNIQUE (ticket_type_id, name)
);


-- ============================================================
-- 10. ORDERS
-- ============================================================

CREATE TABLE orders (
    id UUID PRIMARY KEY DEFAULT uuidv7(),

    user_id UUID NOT NULL,

    event_id UUID NOT NULL,

    order_reference VARCHAR(30) NOT NULL UNIQUE,

    status order_status NOT NULL DEFAULT 'PENDING',

    total_amount NUMERIC(14,2) NOT NULL DEFAULT 0,

    expires_at TIMESTAMPTZ NOT NULL
        DEFAULT (CURRENT_TIMESTAMP + INTERVAL '15 minutes'),

    paid_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_order_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_order_event
        FOREIGN KEY (event_id)
        REFERENCES events(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_order_total
        CHECK (total_amount >= 0)
);


-- ============================================================
-- 11. ORDER ITEMS
-- ============================================================

CREATE TABLE order_items (
    id UUID PRIMARY KEY DEFAULT uuidv7(),

    order_id UUID NOT NULL,

    ticket_type_id UUID NOT NULL,

    ticket_price_id UUID,

    quantity INTEGER NOT NULL,

    unit_price NUMERIC(14,2) NOT NULL,

    subtotal NUMERIC(14,2)
        GENERATED ALWAYS AS (quantity * unit_price) STORED,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_order_item_order
        FOREIGN KEY (order_id)
        REFERENCES orders(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_order_item_ticket_type
        FOREIGN KEY (ticket_type_id)
        REFERENCES ticket_types(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_order_item_ticket_price
        FOREIGN KEY (ticket_price_id)
        REFERENCES ticket_prices(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_order_item_quantity
        CHECK (quantity > 0),

    CONSTRAINT chk_order_item_unit_price
        CHECK (unit_price >= 0)
);


-- ============================================================
-- 12. TICKETS
-- ============================================================

CREATE TABLE tickets (
    id UUID PRIMARY KEY DEFAULT uuidv7(),

    order_id UUID NOT NULL,

    order_item_id UUID NOT NULL,

    ticket_code VARCHAR(40) NOT NULL UNIQUE,

    attendee_name VARCHAR(100) NOT NULL,

    attendee_email VARCHAR(255) NOT NULL,

    status ticket_status NOT NULL DEFAULT 'ACTIVE',

    checked_in_at TIMESTAMPTZ,

    checked_in_by UUID,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_ticket_order
        FOREIGN KEY (order_id)
        REFERENCES orders(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_ticket_order_item
        FOREIGN KEY (order_item_id)
        REFERENCES order_items(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_ticket_checked_in_by
        FOREIGN KEY (checked_in_by)
        REFERENCES users(id)
        ON DELETE SET NULL,

    CONSTRAINT chk_ticket_checkin_data
        CHECK (
            (
                status = 'USED'
                AND checked_in_at IS NOT NULL
                AND checked_in_by IS NOT NULL
            )
            OR
            (
                status <> 'USED'
            )
        )
);


-- ============================================================
-- 13. PAYMENTS
-- ============================================================

CREATE TABLE payments (
    id UUID PRIMARY KEY DEFAULT uuidv7(),

    order_id UUID NOT NULL,

    method payment_method NOT NULL DEFAULT 'MOCK',

    status payment_status NOT NULL DEFAULT 'PENDING',

    amount NUMERIC(14,2) NOT NULL,

    paid_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_payment_order
        FOREIGN KEY (order_id)
        REFERENCES orders(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_payment_amount
        CHECK (amount >= 0)
);


-- ============================================================
-- 14. REFUNDS
-- ============================================================

CREATE TABLE refunds (
    id UUID PRIMARY KEY DEFAULT uuidv7(),

    order_id UUID NOT NULL,

    requested_by UUID NOT NULL,

    processed_by UUID,

    amount NUMERIC(14,2) NOT NULL,

    reason TEXT NOT NULL,

    status refund_status NOT NULL DEFAULT 'PENDING',

    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    processed_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_refund_order
        FOREIGN KEY (order_id)
        REFERENCES orders(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_refund_requester
        FOREIGN KEY (requested_by)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_refund_processor
        FOREIGN KEY (processed_by)
        REFERENCES users(id)
        ON DELETE SET NULL,

    CONSTRAINT chk_refund_amount
        CHECK (amount >= 0)
);


-- ============================================================
-- 15. NOTIFICATIONS
-- ============================================================

CREATE TABLE notifications (
    id UUID PRIMARY KEY DEFAULT uuidv7(),

    user_id UUID NOT NULL,

    type notification_type NOT NULL,

    title VARCHAR(200) NOT NULL,

    message TEXT NOT NULL,

    read_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_notification_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE
);


